@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ProductAddEditScreen(
    viewModel: ProductViewModel,
    productId: Long?,
    userFullName: String,
    onNavigateBack: () -> Unit,
    onSuccess: (String) -> Unit = {}
) {
    val context = LocalContext.current
    val categories by viewModel.categories.collectAsState()

    // Random auto SKU e.g. SKU-K3UTDGTO
    val autoGeneratedSP = remember {
        val chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
        val rand = (1..8).map { chars[Random.nextInt(chars.length)] }.joinToString("")
        "SP-$rand"
    }

    var sku by remember { mutableStateOf(autoGeneratedSP) }
    var productName by remember { mutableStateOf("") }
    var categoryName by remember { mutableStateOf("") }
    var safeStock by remember { mutableStateOf("10") }
    var exportPrice by remember { mutableStateOf("") }
    var description by remember { mutableStateOf("") }
    var status by remember { mutableStateOf("ACTIVE") }
    var selectedImageUri by remember { mutableStateOf<String?>(null) }

    var selectedCategoryId by remember { mutableStateOf<Long?>(null) }
    var showScannerSheet by remember { mutableStateOf(false) }
    var showCategoryDialog by remember { mutableStateOf(false) }
    var errorField by remember { mutableStateOf<String?>(null) }
    var activeSnackbarMessage by remember { mutableStateOf<String?>(null) }
    var snackbarJob by remember { mutableStateOf<Job?>(null) }
    val snackbarHostState = remember { SnackbarHostState() }
    val coroutineScope = rememberCoroutineScope()

    fun showSingleSnackbar(message: String) {
        if (activeSnackbarMessage == message && snackbarHostState.currentSnackbarData != null) {
            return
        }
        snackbarJob?.cancel()
        snackbarJob = coroutineScope.launch {
            snackbarHostState.currentSnackbarData?.dismiss()
            activeSnackbarMessage = message
            snackbarHostState.showSnackbar(
                message = message,
                duration = SnackbarDuration.Short
            )
            activeSnackbarMessage = null
        }
    }

    val photoPickerLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.PickVisualMedia(),
        onResult = { uri ->
            if (uri != null) {
                selectedImageUri = uri.toString()
                try {
                    context.contentResolver.takePersistableUriPermission(
                        uri,
                        Intent.FLAG_GRANT_READ_URI_PERMISSION
                    )
                } catch (e: Exception) {
                    // fall through
                }
            }
        }
    )

    val isEditing = productId != null && productId > 0

    LaunchedEffect(productId) {
        if (isEditing) {
            val item = viewModel.getProductWithDetailsById(productId!!)
            if (item != null) {
                val p = item.product
                sku = p.productCode
                productName = p.productName
                selectedCategoryId = p.categoryId
                val cat = categories.find { it.id == p.categoryId }
                categoryName = cat?.name ?: ""
                safeStock = p.minStock.toString()
                exportPrice = if (p.exportPrice > 0) p.exportPrice.toLong().toString() else ""
                description = p.description
                status = p.status
                selectedImageUri = p.imagePath
            }
        }
    }

    Scaffold(
        contentWindowInsets = WindowInsets(0, 0, 0, 0),
        snackbarHost = {
            SnackbarHost(hostState = snackbarHostState) { data ->
                Snackbar(
                    snackbarData = data,
                    containerColor = Color(0xFF1E293B),
                    contentColor = Color.White,
                    shape = RoundedCornerShape(8.dp)
                )
            }
        },
        bottomBar = {
            Surface(
                shadowElevation = 8.dp,
                color = Color.White,
                modifier = Modifier.fillMaxWidth()
            ) {
                Button(
                    onClick = {
                        if (productName.isBlank()) {
                            errorField = "productName"
                            showSingleSnackbar("Vui lòng nhập tên sản phẩm")
                        } else if (categoryName.isBlank() && (selectedCategoryId == null || selectedCategoryId == 0L)) {
                            errorField = "category"
                            showSingleSnackbar("Bắt buộc phải chọn hoặc nhập Danh mục trước khi lưu sản phẩm")
                        } else {
                            val minStockVal = safeStock.toIntOrNull() ?: 10
                            if (minStockVal < 0) {
                                errorField = "safeStock"
                                showSingleSnackbar("Số lượng tồn tối thiểu phải >= 0")
                                return@Button
                            }

                            errorField = null
                            val p = Product(
                                productId = if (isEditing) productId!! else 0,
                                productCode = sku.trim().ifBlank { autoGeneratedSP },
                                productName = productName.trim(),
                                imagePath = selectedImageUri,
                                exportPrice = exportPrice.toDoubleOrNull() ?: 0.0,
                                minStock = minStockVal,
                                description = description.trim(),
                                status = status
                            )
                            viewModel.saveProductWithCategory(
                                product = p,
                                categoryNameInput = categoryName.trim(),
                                selectedCatId = selectedCategoryId,
                                isEditing = isEditing,
                                onSuccess = {
                                    val msg = if (isEditing) "Sửa sản phẩm thành công" else "Thêm sản phẩm thành công"
                                    onSuccess(msg)
                                },
                                onError = { msg ->
                                    showSingleSnackbar(msg)
                                }
                            )
                        }
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = PrimaryBlue),
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(16.dp)
                        .height(52.dp)
                        .testTag("save_product_btn"),
                    shape = RoundedCornerShape(12.dp)
                ) {
                    Text(
                        text = "LƯU SẢN PHẨM",
                        fontWeight = FontWeight.Bold,
                        fontSize = 16.sp,
                        color = Color.White
                    )
                }
            }
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .background(Color.White)
                .padding(innerPadding)
                .verticalScroll(rememberScrollState())
        ) {
            Spacer(modifier = Modifier.height(8.dp))

            // Photo Picker Section
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(vertical = 8.dp),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                Box(
                    modifier = Modifier
                        .size(120.dp)
                        .clip(RoundedCornerShape(20.dp))
                        .background(Color(0xFFEFF6FF))
                        .clickable {
                            photoPickerLauncher.launch(
                                PickVisualMediaRequest(ActivityResultContracts.PickVisualMedia.ImageOnly)
                            )
                        },
                    contentAlignment = Alignment.Center
                ) {
                    if (!selectedImageUri.isNullOrBlank()) {
                        AsyncImage(
                            model = selectedImageUri,
                            contentDescription = "Ảnh sản phẩm",
                            contentScale = ContentScale.Crop,
                            modifier = Modifier.fillMaxSize()
                        )
                        Box(
                            modifier = Modifier
                                .align(Alignment.TopEnd)
                                .padding(6.dp)
                                .size(28.dp)
                                .clip(CircleShape)
                                .background(Color.Black.copy(alpha = 0.6f))
                                .clickable { selectedImageUri = null },
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.Close,
                                contentDescription = "Xóa ảnh",
                                tint = Color.White,
                                modifier = Modifier.size(16.dp)
                            )
                        }
                    } else {
                        Column(
                            horizontalAlignment = Alignment.CenterHorizontally,
                            verticalArrangement = Arrangement.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.CameraAlt,
                                contentDescription = "Chọn ảnh từ máy",
                                tint = PrimaryBlue,
                                modifier = Modifier.size(38.dp)
                            )
                            Spacer(modifier = Modifier.height(4.dp))
                            Text(
                                text = "+ Chọn ảnh",
                                style = MaterialTheme.typography.labelSmall,
                                color = PrimaryBlue,
                                fontWeight = FontWeight.Bold
                            )
                        }
                    }
                }

                Spacer(modifier = Modifier.height(6.dp))
                Text(
                    text = if (!selectedImageUri.isNullOrBlank()) "Chạm vào ảnh để thay đổi" else "Chọn ảnh sản phẩm từ thiết bị",
                    style = MaterialTheme.typography.labelSmall,
                    color = Color(0xFF64748B)
                )
            }

            Spacer(modifier = Modifier.height(8.dp))

            // Section 1: Thông tin cơ bản
            Card(
                colors = CardDefaults.cardColors(containerColor = Color.White),
                border = BorderStroke(1.dp, if (errorField == "productName") Color(0xFFEF4444) else Color(0xFFDBEAFE)),
                elevation = CardDefaults.cardElevation(defaultElevation = 1.dp),
                shape = RoundedCornerShape(16.dp),
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp)
            ) {
                Column {
                    FormInputRow(
                        label = "Mã SP (Mã QR)",
                        value = sku,
                        onValueChange = { sku = it },
                        placeholder = "Mã sản phẩm / Mã QR",
                        trailingIcon = {
                            IconButton(onClick = { showScannerSheet = true }) {
                                Icon(Icons.Default.QrCodeScanner, contentDescription = "Quét QR", tint = PrimaryBlue)
                            }
                        },
                        modifier = Modifier.testTag("sku_input_row")
                    )
                    HorizontalDivider(color = Color(0xFFF0F0F0))

                    FormInputRow(
                        label = "Tên sản phẩm *",
                        value = productName,
                        onValueChange = {
                            productName = it
                            if (errorField == "productName") errorField = null
                        },
                        placeholder = "Nhập tên sản phẩm",
                        isError = errorField == "productName",
                        errorText = if (errorField == "productName") "Vui lòng nhập tên sản phẩm" else null,
                        modifier = Modifier.testTag("product_name_input_row")
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Section 2: Phân loại sản phẩm
            Card(
                colors = CardDefaults.cardColors(containerColor = Color.White),
                border = BorderStroke(1.dp, if (errorField == "category" || errorField == "safeStock") Color(0xFFEF4444) else Color(0xFFDBEAFE)),
                elevation = CardDefaults.cardElevation(defaultElevation = 1.dp),
                shape = RoundedCornerShape(16.dp),
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp)
            ) {
                Column {
                    Text(
                        text = "Phân loại sản phẩm",
                        fontWeight = FontWeight.Bold,
                        style = MaterialTheme.typography.titleMedium,
                        color = Color(0xFF0F172A),
                        modifier = Modifier.padding(horizontal = 16.dp, vertical = 12.dp)
                    )
                    HorizontalDivider(color = Color(0xFFF0F0F0))

                    FormInputRow(
                        label = "Danh mục *",
                        value = categoryName,
                        onValueChange = {
                            categoryName = it
                            selectedCategoryId = null
                            if (errorField == "category") errorField = null
                        },
                        placeholder = "Bắt buộc chọn hoặc nhập danh mục",
                        isError = errorField == "category",
                        errorText = if (errorField == "category") "Bắt buộc chọn hoặc nhập Danh mục trước khi lưu sản phẩm" else null,
                        trailingIcon = {
                            IconButton(onClick = { showCategoryDialog = true }) {
                                Icon(
                                    imageVector = Icons.Default.FormatListBulleted,
                                    contentDescription = "Chọn danh mục",
                                    tint = PrimaryBlue
                                )
                            }
                        }
                    )
                    HorizontalDivider(color = Color(0xFFF0F0F0))

                    FormInputRow(
                        label = "Tồn kho an toàn",
                        value = safeStock,
                        onValueChange = {
                            safeStock = it
                            if (errorField == "safeStock") errorField = null
                        },
                        placeholder = "Số lượng tối thiểu",
                        keyboardType = KeyboardType.Number,
                        isError = errorField == "safeStock",
                        errorText = if (errorField == "safeStock") "Số lượng tồn tối thiểu phải >= 0" else null
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Section 3: Thông tin giá
            Card(
                colors = CardDefaults.cardColors(containerColor = Color.White),
                border = BorderStroke(1.dp, Color(0xFFDBEAFE)),
                elevation = CardDefaults.cardElevation(defaultElevation = 1.dp),
                shape = RoundedCornerShape(16.dp),
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp)
            ) {
                Column {
                    Text(
                        text = "Thông tin giá",
                        fontWeight = FontWeight.Bold,
                        style = MaterialTheme.typography.titleMedium,
                        color = Color(0xFF0F172A),
                        modifier = Modifier.padding(horizontal = 16.dp, vertical = 12.dp)
                    )
                    HorizontalDivider(color = Color(0xFFF0F0F0))

                    FormInputRow(
                        label = "Giá xuất (bán)",
                        value = exportPrice,
                        onValueChange = { exportPrice = it },
                        placeholder = "0 đ",
                        keyboardType = KeyboardType.Number
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Section 4: Trạng thái & Mô tả
            Card(
                colors = CardDefaults.cardColors(containerColor = Color.White),
                border = BorderStroke(1.dp, Color(0xFFDBEAFE)),
                elevation = CardDefaults.cardElevation(defaultElevation = 1.dp),
                shape = RoundedCornerShape(16.dp),
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp)
            ) {
                Column {
                    Text(
                        text = "Trạng thái & Mô tả",
                        fontWeight = FontWeight.Bold,
                        style = MaterialTheme.typography.titleMedium,
                        color = Color(0xFF0F172A),
                        modifier = Modifier.padding(horizontal = 16.dp, vertical = 12.dp)
                    )
                    HorizontalDivider(color = Color(0xFFF0F0F0))

                    if (isEditing) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(horizontal = 16.dp, vertical = 12.dp),
                            horizontalArrangement = Arrangement.SpaceBetween,
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text(
                                text = "Trạng thái",
                                style = MaterialTheme.typography.bodyMedium,
                                fontWeight = FontWeight.Bold,
                                color = Color(0xFF334155)
                            )
                            Row(verticalAlignment = Alignment.CenterVertically) {
                                FilterChip(
                                    selected = status == "ACTIVE",
                                    onClick = { status = "ACTIVE" },
                                    label = { Text("Đang kinh doanh") },
                                    colors = FilterChipDefaults.filterChipColors(
                                        selectedContainerColor = PrimaryBlue,
                                        selectedLabelColor = Color.White
                                    )
                                )
                                Spacer(modifier = Modifier.width(8.dp))
                                FilterChip(
                                    selected = status == "INACTIVE",
                                    onClick = { status = "INACTIVE" },
                                    label = { Text("Ngừng kinh doanh") },
                                    colors = FilterChipDefaults.filterChipColors(
                                        selectedContainerColor = Color(0xFF64748B),
                                        selectedLabelColor = Color.White
                                    )
                                )
                            }
                        }
                        HorizontalDivider(color = Color(0xFFF0F0F0))
                    }

                    FormInputRow(
                        label = "Mô tả sản phẩm",
                        value = description,
                        onValueChange = { description = it },
                        placeholder = "Ghi chú thêm về sản phẩm..."
                    )

                    HorizontalDivider(color = Color(0xFFF0F0F0))

                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(horizontal = 16.dp, vertical = 12.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Icon(
                            imageVector = Icons.Default.Info,
                            contentDescription = null,
                            tint = Color(0xFF0284C7),
                            modifier = Modifier.size(18.dp)
                        )
                        Spacer(modifier = Modifier.width(8.dp))
                        Text(
                            text = "Số lượng tồn kho được tự động khởi tạo bằng 0 và cập nhật qua các nghiệp vụ Nhập/Xuất/Kiểm kê.",
                            style = MaterialTheme.typography.bodySmall,
                            color = Color(0xFF0369A1)
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.height(32.dp))
        }
    }

    if (showScannerSheet) {
        BarcodeScannerSheet(
            onCodeScanned = { code ->
                sku = code
                showScannerSheet = false
            },
            onDismiss = { showScannerSheet = false }
        )
    }

    if (showCategoryDialog) {
        var newCatInput by remember { mutableStateOf("") }
        var searchCatQuery by remember { mutableStateOf("") }
        var isCreating by remember { mutableStateOf(false) }

        val filteredCategories = remember(categories, searchCatQuery) {
            if (searchCatQuery.isBlank()) categories
            else categories.filter { it.name.contains(searchCatQuery, ignoreCase = true) }
        }

        Dialog(onDismissRequest = { showCategoryDialog = false }) {
            Card(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(vertical = 16.dp),
                shape = RoundedCornerShape(20.dp),
                colors = CardDefaults.cardColors(containerColor = Color.White),
                border = BorderStroke(1.dp, Color(0xFFDBEAFE))
            ) {
                Column(
                    modifier = Modifier
                        .padding(20.dp)
                        .fillMaxWidth()
                ) {
                    // Header
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(
                                imageVector = Icons.Default.FormatListBulleted,
                                contentDescription = null,
                                tint = PrimaryBlue,
                                modifier = Modifier.size(24.dp)
                            )
                            Spacer(modifier = Modifier.width(8.dp))
                            Text(
                                text = "Chọn Danh Mục",
                                style = MaterialTheme.typography.titleLarge,
                                fontWeight = FontWeight.Bold,
                                color = Color(0xFF0F172A)
                            )
                        }
                        IconButton(onClick = { showCategoryDialog = false }) {
                            Icon(Icons.Default.Close, contentDescription = "Đóng", tint = Color(0xFF64748B))
                        }
                    }

                    Spacer(modifier = Modifier.height(12.dp))

                    // Section: Quick Create
                    Surface(
                        color = Color(0xFFF0F9FF),
                        shape = RoundedCornerShape(12.dp),
                        border = BorderStroke(1.dp, Color(0xFFBAE6FD)),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Column(modifier = Modifier.padding(12.dp)) {
                            Text(
                                text = "Tạo danh mục mới nhanh:",
                                fontSize = 12.sp,
                                fontWeight = FontWeight.Bold,
                                color = PrimaryBlue
                            )
                            Spacer(modifier = Modifier.height(6.dp))
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                OutlinedTextField(
                                    value = newCatInput,
                                    onValueChange = { newCatInput = it },
                                    placeholder = { Text("Tên danh mục mới...", fontSize = 13.sp, color = Color(0xFF94A3B8)) },
                                    singleLine = true,
                                    modifier = Modifier.weight(1f),
                                    shape = RoundedCornerShape(10.dp),
                                    colors = OutlinedTextFieldDefaults.colors(
                                        focusedContainerColor = Color.White,
                                        unfocusedContainerColor = Color.White,
                                        focusedBorderColor = PrimaryBlue,
                                        unfocusedBorderColor = Color(0xFFCBD5E1)
                                    )
                                )
                                Spacer(modifier = Modifier.width(8.dp))
                                Button(
                                    onClick = {
                                        if (newCatInput.isNotBlank() && !isCreating) {
                                            isCreating = true
                                            coroutineScope.launch {
                                                try {
                                                    val cat = viewModel.addCategoryQuick(newCatInput)
                                                    selectedCategoryId = cat.id
                                                    categoryName = cat.name
                                                    showCategoryDialog = false
                                                } finally {
                                                    isCreating = false
                                                }
                                            }
                                        }
                                    },
                                    enabled = newCatInput.isNotBlank() && !isCreating,
                                    colors = ButtonDefaults.buttonColors(containerColor = PrimaryBlue),
                                    shape = RoundedCornerShape(10.dp),
                                    contentPadding = PaddingValues(horizontal = 14.dp, vertical = 10.dp)
                                ) {
                                    Icon(Icons.Default.Add, contentDescription = null, modifier = Modifier.size(16.dp))
                                    Spacer(modifier = Modifier.width(4.dp))
                                    Text("Tạo", fontSize = 13.sp, fontWeight = FontWeight.Bold)
                                }
                            }
                        }
                    }

                    Spacer(modifier = Modifier.height(14.dp))
                    HorizontalDivider(color = Color(0xFFE2E8F0))
                    Spacer(modifier = Modifier.height(10.dp))

                    // Search box
                    OutlinedTextField(
                        value = searchCatQuery,
                        onValueChange = { searchCatQuery = it },
                        placeholder = { Text("Tìm danh mục sẵn có...", fontSize = 13.sp, color = Color(0xFF94A3B8)) },
                        leadingIcon = { Icon(Icons.Default.Search, contentDescription = null, tint = Color(0xFF94A3B8), modifier = Modifier.size(18.dp)) },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(10.dp),
                        colors = OutlinedTextFieldDefaults.colors(
                            focusedBorderColor = PrimaryBlue,
                            unfocusedBorderColor = Color(0xFFE2E8F0)
                        )
                    )

                    Spacer(modifier = Modifier.height(10.dp))

                    // List with fixed height for ~5 items visible (~250.dp max) and LazyColumn scrolling
                    Box(
                        modifier = Modifier
                            .fillMaxWidth()
                            .heightIn(max = 250.dp)
                    ) {
                        if (filteredCategories.isEmpty()) {
                            Box(
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .padding(vertical = 24.dp),
                                contentAlignment = Alignment.Center
                            ) {
                                Text(
                                    text = if (searchCatQuery.isBlank()) "Chưa có danh mục nào. Hãy nhập tên ở trên để tạo mới!" else "Không tìm thấy danh mục phù hợp",
                                    color = Color(0xFF94A3B8),
                                    fontSize = 13.sp
                                )
                            }
                        } else {
                            LazyColumn(
                                verticalArrangement = Arrangement.spacedBy(4.dp)
                            ) {
                                items(filteredCategories, key = { it.id }) { cat ->
                                    val isSelected = cat.id == selectedCategoryId || cat.name.equals(categoryName, ignoreCase = true)
                                    Surface(
                                        color = if (isSelected) Color(0xFFEFF6FF) else Color.Transparent,
                                        shape = RoundedCornerShape(10.dp),
                                        border = if (isSelected) BorderStroke(1.dp, Color(0xFFBFDBFE)) else null,
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .clickable {
                                                selectedCategoryId = cat.id
                                                categoryName = cat.name
                                                if (errorField == "category") errorField = null
                                                showCategoryDialog = false
                                            }
                                    ) {
                                        Row(
                                            modifier = Modifier.padding(horizontal = 12.dp, vertical = 12.dp),
                                            verticalAlignment = Alignment.CenterVertically,
                                            horizontalArrangement = Arrangement.SpaceBetween
                                        ) {
                                            Row(verticalAlignment = Alignment.CenterVertically) {
                                                Box(
                                                    modifier = Modifier
                                                        .size(8.dp)
                                                        .clip(CircleShape)
                                                        .background(if (isSelected) PrimaryBlue else Color(0xFFCBD5E1))
                                                )
                                                Spacer(modifier = Modifier.width(10.dp))
                                                Text(
                                                    text = cat.name,
                                                    style = MaterialTheme.typography.bodyMedium,
                                                    color = if (isSelected) PrimaryBlue else Color(0xFF0F172A),
                                                    fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal
                                                )
                                            }
                                            if (isSelected) {
                                                Icon(
                                                    imageVector = Icons.Default.Check,
                                                    contentDescription = null,
                                                    tint = PrimaryBlue,
                                                    modifier = Modifier.size(18.dp)
                                                )
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }

                    Spacer(modifier = Modifier.height(12.dp))

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.End
                    ) {
                        TextButton(onClick = { showCategoryDialog = false }) {
                            Text("Đóng", color = Color(0xFF64748B), fontWeight = FontWeight.SemiBold)
                        }
                    }
                }
            }
        }
    }


