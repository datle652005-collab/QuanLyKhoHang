@Composable
fun FormInputRow(
    label: String,
    value: String,
    onValueChange: (String) -> Unit,
    placeholder: String,
    keyboardType: KeyboardType = KeyboardType.Text,
    readOnly: Boolean = false,
    trailingIcon: (@Composable () -> Unit)? = null,
    onClick: (() -> Unit)? = null,
    isError: Boolean = false,
    errorText: String? = null,
    modifier: Modifier = Modifier
) {
    Column(
        modifier = modifier
            .fillMaxWidth()
            .background(if (isError) Color(0xFFFEF2F2) else Color.Transparent)
    ) {
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .clickable(enabled = onClick != null) { onClick?.invoke() }
                .padding(horizontal = 16.dp, vertical = 10.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Text(
                text = label,
                style = MaterialTheme.typography.bodyMedium,
                fontWeight = FontWeight.Medium,
                color = if (isError) Color(0xFFDC2626) else Color(0xFF334155),
                modifier = Modifier.weight(1f)
            )

            Box(
                modifier = Modifier.weight(1.5f),
                contentAlignment = Alignment.CenterEnd
            ) {
                TextField(
                    value = value,
                    onValueChange = onValueChange,
                    readOnly = readOnly || onClick != null,
                    placeholder = { Text(placeholder, color = if (isError) Color(0xFFF87171) else Color(0xFF94A3B8), fontSize = 14.sp) },
                    singleLine = true,
                    keyboardOptions = KeyboardOptions(keyboardType = keyboardType),
                    colors = TextFieldDefaults.colors(
                        focusedContainerColor = Color.Transparent,
                        unfocusedContainerColor = Color.Transparent,
                        disabledContainerColor = Color.Transparent,
                        focusedIndicatorColor = Color.Transparent,
                        unfocusedIndicatorColor = Color.Transparent
                    ),
                    textStyle = LocalTextStyle.current.copy(
                        fontWeight = FontWeight.SemiBold,
                        fontSize = 15.sp,
                        color = if (isError) Color(0xFFDC2626) else Color(0xFF0F172A)
                    )
                )
            }

            if (trailingIcon != null) {
                trailingIcon()
            } else {
                Icon(
                    imageVector = Icons.Default.ChevronRight,
                    contentDescription = null,
                    tint = if (isError) Color(0xFFF87171) else Color(0xFFCBD5E1),
                    modifier = Modifier.size(20.dp)
                )
            }
        }
        if (isError && !errorText.isNullOrBlank()) {
            Text(
                text = errorText,
                color = Color(0xFFDC2626),
                fontSize = 12.sp,
                fontWeight = FontWeight.Medium,
                modifier = Modifier.padding(start = 16.dp, end = 16.dp, bottom = 8.dp)
            )
        }
    }
}
